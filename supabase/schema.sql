CREATE TABLE IF NOT EXISTS public.assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    subject TEXT NOT NULL,
    due_date DATE,
    total_marks INTEGER NOT NULL CHECK (total_marks > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    original_filename TEXT,
    storage_path TEXT,
    mime_type TEXT,
    ocr_text TEXT NOT NULL DEFAULT '',
    ocr_method TEXT NOT NULL DEFAULT 'none',
    file_size BIGINT,
    created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL
);

ALTER TABLE public.assignments
    ADD COLUMN IF NOT EXISTS original_filename TEXT,
    ADD COLUMN IF NOT EXISTS storage_path TEXT,
    ADD COLUMN IF NOT EXISTS mime_type TEXT,
    ADD COLUMN IF NOT EXISTS ocr_text TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS ocr_method TEXT NOT NULL DEFAULT 'none',
    ADD COLUMN IF NOT EXISTS file_size BIGINT,
    ADD COLUMN IF NOT EXISTS created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS public.evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL
        CONSTRAINT evaluations_assignment_id_fkey
        REFERENCES public.assignments(id) ON DELETE CASCADE,
    student_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    student TEXT NOT NULL,
    score NUMERIC CHECK (score IS NULL OR score >= 0),
    status TEXT NOT NULL CHECK (
        status IN ('approved', 'ai_evaluated', 'pending', 'rejected')
    ),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.evaluations
    DROP CONSTRAINT IF EXISTS evaluations_status_check;
ALTER TABLE public.evaluations
    ADD CONSTRAINT evaluations_status_check
    CHECK (status IN ('approved', 'ai_evaluated', 'pending', 'rejected'));

ALTER TABLE public.evaluations
    ADD COLUMN IF NOT EXISTS student_id UUID
    REFERENCES auth.users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS ai_feedback TEXT;

ALTER TABLE public.assignments
    ADD COLUMN IF NOT EXISTS key_answer_text TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_evaluations_submitted_at
    ON public.evaluations(submitted_at);
CREATE INDEX IF NOT EXISTS idx_evaluations_status
    ON public.evaluations(status);
CREATE INDEX IF NOT EXISTS idx_evaluations_student_id
    ON public.evaluations(student_id);

ALTER TABLE public.assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evaluations ENABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.assignments, public.evaluations TO service_role;
GRANT USAGE, SELECT ON SEQUENCE
    public.assignments_id_seq, public.evaluations_id_seq TO service_role;

CREATE TABLE IF NOT EXISTS public.submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES public.assignments(id) ON DELETE CASCADE,
    student_id TEXT NOT NULL,
    student_name TEXT NOT NULL,
    answer_text TEXT NOT NULL DEFAULT '',
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

GRANT ALL ON TABLE public.submissions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.submissions_id_seq TO service_role;

